create function private.batch_take_cost(p_batch_id uuid,p_quantity integer) returns numeric
language sql security invoker set search_path='' as $$
  select case when b.total_cost is null then null
    else round((b.total_cost-coalesce(b.written_off_cost,0)-coalesce(a.cost,0))*p_quantity /
      nullif(b.quantity-b.written_off-coalesce(a.quantity,0),0),2) end
  from public.inventory_cost_batches b
  left join lateral(select sum(quantity) quantity,sum(cost_amount) cost from public.inventory_cost_allocations where batch_id=b.id) a on true
  where b.id=p_batch_id
$$;
revoke all on function private.batch_take_cost(uuid,integer) from public,anon,authenticated;

create function private.normalize_batch_total() returns trigger
language plpgsql security invoker set search_path='' as $$
begin
  if tg_op='INSERT' then
    if new.total_cost is null and new.unit_cost is not null then new.total_cost:=round(new.unit_cost*new.quantity,2); end if;
  elsif new.total_cost is not distinct from old.total_cost and new.unit_cost is distinct from old.unit_cost then
    new.total_cost:=round(new.unit_cost*new.quantity,2);
  end if;
  if new.total_cost is not null then new.unit_cost:=round(new.total_cost/new.quantity,8); end if;
  if tg_op='INSERT' then new.written_off_cost:=round(new.total_cost*new.written_off/new.quantity,2); end if;
  return new;
end;
$$;
revoke all on function private.normalize_batch_total() from public,anon,authenticated;
create trigger normalize_batch_total before insert or update on public.inventory_cost_batches
for each row execute function private.normalize_batch_total();

create function private.reprice_batch_allocations() returns trigger
language plpgsql security definer set search_path='' as $$
declare v_row record; v_remaining numeric; v_quantity integer; v_cost numeric;
begin
  if new.total_cost is not distinct from old.total_cost and new.quantity=old.quantity then return null; end if;
  if (select auth.uid()) is null then raise exception 'owner access required'; end if;
  if exists(select 1 from public.inventory_cost_allocations a join public.order_items oi on oi.id=a.order_item_id
    join public.settlement_orders so on so.order_id=oi.order_id where a.batch_id=new.id) then raise exception 'settled batch cost is locked'; end if;
  v_remaining:=new.total_cost-round(new.total_cost*new.written_off/new.quantity,2);
  v_quantity:=new.quantity-new.written_off;
  update public.inventory_cost_batches set written_off_cost=new.total_cost-v_remaining where id=new.id;
  for v_row in select a.* from public.inventory_cost_allocations a join public.order_items oi on oi.id=a.order_item_id
    join public.orders o on o.id=oi.order_id where a.batch_id=new.id order by coalesce(o.packed_at,o.created_at),o.id,oi.id loop
    v_cost:=round(v_remaining*v_row.quantity/nullif(v_quantity,0),2);
    update public.inventory_cost_allocations set cost_amount=v_cost where batch_id=new.id and order_item_id=v_row.order_item_id;
    v_remaining:=v_remaining-v_cost; v_quantity:=v_quantity-v_row.quantity;
  end loop;
  return null;
end;
$$;
revoke all on function private.reprice_batch_allocations() from public,anon,authenticated;
create trigger reprice_batch_allocations after update of total_cost,unit_cost,quantity on public.inventory_cost_batches
for each row execute function private.reprice_batch_allocations();

