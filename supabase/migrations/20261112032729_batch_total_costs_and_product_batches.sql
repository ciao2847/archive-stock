create function private.split_cost_batch(p_source uuid,p_parts jsonb) returns void
language plpgsql security invoker set search_path='' as $$
declare b public.inventory_cost_batches; part jsonb; v_id uuid; v_ids uuid[]:='{}'; v_allocations jsonb;
  a jsonb; child record; v_left integer; v_take integer; v_cost numeric; v_time timestamptz; v_part integer:=0;
begin
  select * into b from public.inventory_cost_batches where id=p_source for update;
  if jsonb_array_length(p_parts)<2 or (select sum((x->>'quantity')::integer) from jsonb_array_elements(p_parts) x)<>b.quantity then raise exception 'split quantity mismatch'; end if;
  if exists(select 1 from public.inventory_cost_allocations a join public.order_items oi on oi.id=a.order_item_id join public.settlement_orders so on so.order_id=oi.order_id where a.batch_id=b.id) then raise exception 'settled batch cost is locked'; end if;
  select coalesce(jsonb_agg(jsonb_build_object('item',a.order_item_id,'quantity',a.quantity) order by coalesce(o.packed_at,o.created_at),o.id,oi.id),'[]') into v_allocations
    from public.inventory_cost_allocations a join public.order_items oi on oi.id=a.order_item_id join public.orders o on o.id=oi.order_id where a.batch_id=b.id;
  delete from public.inventory_cost_allocations where batch_id=b.id;
  for part in select value from jsonb_array_elements(p_parts) loop
    v_part:=v_part+1;
    v_time:=case when (b.received_at at time zone 'Asia/Taipei')::date=(part->>'date')::date then b.received_at else (part->>'date')::timestamp at time zone 'Asia/Taipei' end;
    -- A split retains its original FIFO position, even beside same-day receipts.
    insert into public.inventory_cost_batches(owner_id,product_id,quantity,total_cost,received_at,notes,fifo_position,fifo_path) overriding system value
      values(b.owner_id,b.product_id,(part->>'quantity')::integer,(part->>'totalCost')::numeric,v_time,part->>'notes',b.fifo_position,b.fifo_path||v_part) returning id into v_id;
    v_ids:=array_append(v_ids,v_id);
  end loop;
  v_left:=b.written_off;
  if v_left>0 then
    for child in select * from public.inventory_cost_batches where id=any(v_ids) order by received_at,fifo_position,fifo_path,id loop
      v_take:=least(v_left,child.quantity);v_cost:=private.batch_take_cost(child.id,v_take);
      update public.inventory_cost_batches set written_off=v_take,written_off_cost=v_cost where id=child.id;
      v_left:=v_left-v_take;exit when v_left=0;
    end loop;
  end if;
  for a in select value from jsonb_array_elements(v_allocations) loop
    v_left:=(a->>'quantity')::integer;
    for child in select c.*,c.quantity-c.written_off-coalesce((select sum(quantity) from public.inventory_cost_allocations where batch_id=c.id),0) available
      from public.inventory_cost_batches c where id=any(v_ids) order by received_at,fifo_position,fifo_path,id loop
      v_take:=least(v_left,child.available);if v_take<=0 then continue;end if;
      v_cost:=private.batch_take_cost(child.id,v_take);
      insert into public.inventory_cost_allocations(batch_id,order_item_id,quantity,cost_amount) values(child.id,(a->>'item')::uuid,v_take,v_cost);
      v_left:=v_left-v_take;exit when v_left=0;
    end loop;
    if v_left<>0 then raise exception 'split quantity mismatch'; end if;
  end loop;
  delete from public.inventory_cost_batches where id=b.id;
end;
$$;
revoke all on function private.split_cost_batch(uuid,jsonb) from public,anon,authenticated;

create function private.save_inventory_product_batches(p_input jsonb,p_owner_id uuid default null,p_product_id uuid default null) returns uuid
language plpgsql security definer set search_path='' as $$
declare v_owner uuid; v_id uuid; v_stock integer:=0; v_new integer:=0; v_rows jsonb; r jsonb; b public.inventory_cost_batches;
  v_normal integer; v_split integer; v_parts jsonb; v_images text[]; v_crafts text[]; v_total numeric; v_time timestamptz;
begin
  if (select auth.uid()) is null or coalesce((select public.my_role())::text,'') not in ('admin','staff') then raise exception 'owner access required'; end if;
  if p_product_id is null then v_owner:=p_owner_id;
  else select owner_id,stock into v_owner,v_stock from public.products where id=p_product_id for update;
    if not found then raise exception 'product not found';end if;
    if p_owner_id is not null and p_owner_id is distinct from v_owner then raise exception 'owner access required';end if;
  end if;
  if v_owner is null or (v_owner is distinct from (select private.current_inventory_owner_id()) and (select public.my_role())<>'admin') then raise exception 'owner access required';end if;
  if not exists(select 1 from public.inventory_databases where id=v_owner and accounting_mode='product_fifo') then raise exception 'inventory uses period costs';end if;
  v_rows:=p_input->'costBatches';
  if jsonb_typeof(v_rows) is distinct from 'array' or jsonb_array_length(v_rows)>500 then raise exception 'invalid cost batches';end if;
  for r in select value from jsonb_array_elements(v_rows) loop
    if not (r ?& array['quantity','totalCost','date','notes']) or jsonb_typeof(r->'quantity')<>'number'
      or (r->>'quantity')::numeric not between 1 and 1000000 or (r->>'quantity')::numeric<>trunc((r->>'quantity')::numeric)
      or jsonb_typeof(r->'totalCost') not in ('null','number') or (r->>'totalCost')::numeric<0
      or (r->>'totalCost')::numeric>9999999999.99 or (r->>'totalCost')::numeric<>round((r->>'totalCost')::numeric,2)
      or jsonb_typeof(r->'date')<>'string' or (r->>'date')!~ '^\d{4}-\d{2}-\d{2}$'
      or (r->>'date')::date not between '2000-01-01'::date and (now() at time zone 'Asia/Taipei')::date
      or jsonb_typeof(r->'notes')<>'string' or length(r->>'notes')>1000 or (r ? 'id' and r ? 'sourceBatchId') then raise exception 'invalid cost batches';end if;
    if r ? 'id' or r ? 'sourceBatchId' then
      select * into b from public.inventory_cost_batches where id=coalesce(r->>'id',r->>'sourceBatchId')::uuid and product_id=p_product_id for update;
      if not found then raise exception 'cost batch not found';end if;
      if b.revision is distinct from (r->>'expectedRevision')::integer then raise exception 'cost batch changed; reload';end if;
      if r ? 'id' and ((r->>'quantity')::integer<>b.quantity or (r->>'date')::date<>(b.received_at at time zone 'Asia/Taipei')::date) then raise exception 'existing batch identity cannot change';end if;
    else v_new:=v_new+(r->>'quantity')::integer;end if;
  end loop;
  for b in select * from public.inventory_cost_batches where product_id=p_product_id order by id for update loop
    select count(*) into v_normal from jsonb_array_elements(v_rows) x where x->>'id'=b.id::text;
    select count(*),jsonb_agg(x) into v_split,v_parts from jsonb_array_elements(v_rows) x where x->>'sourceBatchId'=b.id::text;
    if not (v_normal=1 and v_split=0 or v_normal=0 and v_split>=2) then raise exception 'cost batch list changed; reload';end if;
    if v_split>0 and (select sum((x->>'quantity')::integer) from jsonb_array_elements(v_parts) x)<>b.quantity then raise exception 'split quantity mismatch';end if;
  end loop;
  if v_stock+v_new not between 0 and 1000 then raise exception 'invalid cost batches';end if;
  if (p_input->>'stock')::integer is distinct from v_stock+v_new then raise exception 'inventory changed; reload';end if;
  if jsonb_typeof(p_input->'imagePaths')='array' then v_images:=array(select jsonb_array_elements_text(p_input->'imagePaths'));end if;
  if jsonb_typeof(p_input->'crafts')='array' then v_crafts:=array(select jsonb_array_elements_text(p_input->'crafts'));end if;
  if p_input ? 'preorderItemName' and (p_product_id is not null or (p_input->>'stock')::integer=0) then v_id:=public.save_named_inventory_product(p_input,v_owner,p_product_id);
  elsif p_product_id is null then
    v_id:=public.create_inventory_product(p_name=>p_input->>'name',p_work=>p_input->>'work',p_category=>p_input->>'category',p_country=>p_input->>'country',p_source=>p_input->>'source',p_location=>p_input->>'location',p_stock=>(p_input->>'stock')::integer,p_price=>(p_input->>'price')::numeric,p_cost=>0,p_image_paths=>v_images,p_poster_format=>p_input->>'format',p_poster_size=>p_input->>'size',p_poster_crafts=>v_crafts,p_identifying_features=>p_input->>'feature',p_owner_id=>v_owner,p_description=>p_input->>'description');
  else
    if not public.update_inventory_product(p_product_id=>p_product_id,p_name=>p_input->>'name',p_category=>p_input->>'category',p_country=>p_input->>'country',p_source=>p_input->>'source',p_location=>p_input->>'location',p_stock=>(p_input->>'stock')::integer,p_price=>(p_input->>'price')::numeric,p_cost=>null,p_poster_format=>p_input->>'format',p_poster_size=>p_input->>'size',p_identifying_features=>p_input->>'feature',p_work=>p_input->>'work',p_poster_crafts=>v_crafts,p_image_paths=>v_images,p_description=>p_input->>'description') then raise exception 'product not updated';end if;
    v_id:=p_product_id;
  end if;
  if p_product_id is null and p_input ? 'preorderItemName' then update public.products set preorder_item_name=btrim(p_input->>'preorderItemName') where id=v_id;end if;
  -- Materialize explicit receipts before deferred stock reconciliation runs.
  for r in select value from jsonb_array_elements(v_rows) loop
    if r ? 'id' then
      select * into b from public.inventory_cost_batches where id=(r->>'id')::uuid;
      if b.total_cost is distinct from (r->>'totalCost')::numeric or b.notes is distinct from r->>'notes' then
        perform private.save_inventory_batch_total(b.id,(r->>'totalCost')::numeric,r->>'notes',(r->>'expectedRevision')::integer);
      end if;
    elsif not (r ? 'sourceBatchId') then
      v_time:=(r->>'date')::timestamp at time zone 'Asia/Taipei';
      select greatest(v_time,coalesce(max(received_at),v_time)) into v_time from public.inventory_cost_batches where product_id=v_id and (received_at at time zone 'Asia/Taipei')::date=(r->>'date')::date;
      insert into public.inventory_cost_batches(owner_id,product_id,quantity,total_cost,received_at,notes) values(v_owner,v_id,(r->>'quantity')::integer,(r->>'totalCost')::numeric,v_time,r->>'notes');
    end if;
  end loop;
  for b in select * from public.inventory_cost_batches where product_id=v_id and id in (select (x->>'sourceBatchId')::uuid from jsonb_array_elements(v_rows) x where x ? 'sourceBatchId') order by id loop
    select jsonb_agg(x.value order by x.ordinality) into v_parts from jsonb_array_elements(v_rows) with ordinality x(value,ordinality) where x.value->>'sourceBatchId'=b.id::text;
    perform private.split_cost_batch(b.id,v_parts);
  end loop;
  update public.products set purchase_unit_cost=null where id=v_id;
  perform private.sync_product_fifo(v_id);
  return v_id;
end;
